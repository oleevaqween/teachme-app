export function detectMessageIntent(message: string): 'lecture' | 'qa' {
  const normalised = message.trim().toLowerCase();
  if (normalised === '') return 'qa';
  return RESUME_LESSON_PHRASES.includes(normalised) ? 'lecture' : 'qa';
}
