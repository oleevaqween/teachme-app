// src/lib/journey-map-generator/stage-assignment.ts

import type { RawChunk } from './content-chunker';
import type { Stage, ContentChunk } from './index';

/**
 * Generates a unique ID for a content chunk.
 */
function generateChunkId(index: number, timestamp: Date): string {
  const timeStr = timestamp.getTime().toString(36);
  const random = Math.random().toString(36).slice(2, 8);
  return `ck-${timeStr}-${random}-${index}`;
}

/**
 * Tokenizes text into meaningful keywords (lowercase, 3+ chars, no stop words).
 */
function extractKeywords(text: string): Set<string> {
  const stopWords = new Set([
    'the', 'and', 'for', 'are', 'but', 'not', 'you', 'all', 'can', 'had',
    'her', 'was', 'one', 'our', 'out', 'has', 'have', 'been', 'some', 'them',
    'than', 'its', 'over', 'also', 'that', 'this', 'with', 'from', 'what',
    'how', 'why', 'when', 'where', 'which', 'who', 'will', 'would', 'could',
    'should', 'does', 'about', 'more', 'into', 'just', 'tell', 'explain',
    'please', 'know', 'think', 'like', 'each', 'make', 'way', 'may', 'use',
    'used', 'using', 'such', 'they', 'these', 'those', 'other', 'then',
    'there', 'their', 'being', 'only', 'most', 'very', 'many', 'well',
    'through', 'between', 'after', 'before', 'during', 'within', 'without',
  ]);

  const words = text
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 3 && !stopWords.has(w));

  return new Set(words);
}

/**
 * Computes a relevance score between a chunk and a stage based on keyword overlap.
 * Higher score = more relevant match.
 */
function computeRelevanceScore(chunk: RawChunk, stage: Stage): number {
  // Extract keywords from chunk content and source section title
  const chunkKeywords = extractKeywords(chunk.content + ' ' + chunk.sourceSection);

  let score = 0;

  // Score from topicsCovered (highest weight — direct topic matches)
  for (const topic of stage.topicsCovered) {
    const topicKeywords = extractKeywords(topic);
    for (const keyword of topicKeywords) {
      if (chunkKeywords.has(keyword)) {
        score += 3;
      }
    }
  }

  // Score from stage title (medium weight)
  const titleKeywords = extractKeywords(stage.title);
  for (const keyword of titleKeywords) {
    if (chunkKeywords.has(keyword)) {
      score += 2;
    }
  }

  // Score from stage theme (lower weight)
  const themeKeywords = extractKeywords(stage.theme);
  for (const keyword of themeKeywords) {
    if (chunkKeywords.has(keyword)) {
      score += 1;
    }
  }

  return score;
}

/**
 * Assigns content chunks to stages using keyword-based relevance matching.
 *
 * This is an instant operation (no LLM calls) that:
 * 1. Scores each chunk against each stage based on keyword overlap
 * 2. Assigns each chunk to the stage(s) with the highest relevance score
 * 3. Ensures no chunk is orphaned (minimum 1 assignment per chunk)
 * 4. Allows multi-stage assignment when a chunk is highly relevant to multiple stages
 *
 * This approach follows the RAG pattern — the full content is available
 * during teaching sessions, not during organization.
 *
 * @param chunks - Raw chunks produced by the content chunker
 * @param stages - Stages generated by the stage generator
 * @returns ContentChunk objects with stage assignments
 */
export async function assignChunksToStages(
  chunks: RawChunk[],
  stages: Stage[]
): Promise<ContentChunk[]> {
  if (chunks.length === 0 || stages.length === 0) {
    return [];
  }

  console.log(`[stage-assignment] Assigning ${chunks.length} chunks to ${stages.length} stages using keyword matching`);

  const stageOrderCounters = new Map<string, number>();
  const timestamp = new Date();
  const contentChunks: ContentChunk[] = [];

  for (let i = 0; i < chunks.length; i++) {
    const chunk = chunks[i];

    // Score this chunk against all stages
    const scores: { stageId: string; score: number }[] = stages.map((stage) => ({
      stageId: stage.id,
      score: computeRelevanceScore(chunk, stage),
    }));

    // Sort by score descending
    scores.sort((a, b) => b.score - a.score);

    // Assign to top stage(s)
    // Primary: always assign to the best match
    // Secondary: also assign to other stages with score >= 70% of the best
    const bestScore = scores[0].score;
    const threshold = bestScore > 0 ? bestScore * 0.7 : 0;

    const assignedStageIds: string[] = [];

    if (bestScore === 0) {
      // No keyword overlap at all — assign to the stage that covers the broadest topics
      // (or just the first stage as a fallback)
      assignedStageIds.push(scores[0].stageId);
    } else {
      for (const { stageId, score } of scores) {
        if (score >= threshold && score > 0) {
          assignedStageIds.push(stageId);
        }
        // Cap multi-assignment at 3 stages max
        if (assignedStageIds.length >= 3) break;
      }
    }

    // Ensure at least one assignment
    if (assignedStageIds.length === 0) {
      assignedStageIds.push(stages[0].id);
    }

    // Create ContentChunk objects
    for (const stageId of assignedStageIds) {
      const currentOrder = (stageOrderCounters.get(stageId) || 0) + 1;
      stageOrderCounters.set(stageId, currentOrder);

      contentChunks.push({
        id: generateChunkId(contentChunks.length, timestamp),
        stageId,
        journeyId: stages[0].journeyId,
        content: chunk.content,
        sourceDocument: chunk.sourceDocument,
        sourceSection: chunk.sourceSection,
        order: currentOrder,
        wordCount: chunk.wordCount,
      });
    }
  }

  console.log(`[stage-assignment] Created ${contentChunks.length} chunk assignments (${chunks.length} chunks across ${stages.length} stages)`);

  return contentChunks;
}
